r"""Build the portable executable with PyInstaller (one folder per OS).

    .venv/bin/python build.py            # Linux/macOS -> dist/eo-stt/
    .venv\Scripts\python.exe build.py    # Windows -> dist\eo-stt\

What the bundle contains:
- Python runtime + app code + GUI (customtkinter/Tk) + numpy + soundfile.
- CPU-only ONNX Runtime + onnx-asr (no torch, NeMo, CUDA or TensorRT).
- The INT8 ASR model (~142 MB) in dist/eo-stt/model/, beside the executable.
  It is fetched at BUILD time by fetch_model.py (pinned HF commit, sha256
  verified); the app itself never downloads anything at runtime.

PyInstaller cannot cross-compile: run this once per target OS (Linux, Windows,
macOS). .github/workflows/build.yml does exactly that in CI.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from fetch_model import MODEL_DIR, fetch_model  # noqa: E402

# Packages whose data/submodules/native libs PyInstaller's static analysis misses.
COLLECT_ALL = [
    "customtkinter",   # themes, fonts, assets
    "onnx_asr",        # preprocessors/data/*.onnx + fbanks.npz (read via importlib.resources)
    "onnxruntime",     # libonnxruntime + pybind state (CPU-only wheel)
    "soundfile",       # libsndfile binary (mp3/wav/ogg/flac decoding)
    "darkdetect",      # customtkinter's system-dark-mode probe
]

# dist metadata read via importlib.metadata at import time
COPY_METADATA = ["onnx-asr", "onnxruntime", "customtkinter"]

# Not used at runtime. Do NOT exclude stdlib test modules (unittest/pydoc):
# numpy.testing imports unittest and the frozen app crashed without it.
EXCLUDE = [
    "torch",
    "torchvision",
    "torchaudio",
    "nemo",
    "nemo_toolkit",
    "scipy",
    "pandas",
    "matplotlib",
    "IPython",
    "jupyter",
    "huggingface_hub",
    "cuda",
    "tensorrt",
    "tkinter.test",
]

SPEC_TEMPLATE = """# -*- mode: python ; coding: utf-8 -*-
# Generated by build.py — do not edit (gitignored build byproduct).
from PyInstaller.utils.hooks import collect_all, copy_metadata

datas = []
binaries = []
hiddenimports = []
for pkg in {collect_all!r}:
    d, b, h = collect_all(pkg)
    datas += d
    binaries += b
    hiddenimports += h
for dist in {copy_metadata!r}:
    datas += copy_metadata(dist)

a = Analysis(
    [{main_py!r}],
    pathex=[{root!r}],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hooksconfig={{}},
    runtime_hooks=[],
    excludes={exclude!r},
    noarchive=False,
    optimize=0,
)
pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name={name!r},
    debug=False,
    bootloader_ignore_signals=False,
    strip=True,
    upx=False,
    console=True,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=True,
    upx=False,
    upx_exclude=[],
    name={name!r},
)
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--name", default="eo-stt")
    ap.add_argument("--skip-model-fetch", action="store_true",
                    help="do not download the model if missing (fail instead)")
    args = ap.parse_args()

    if not args.skip_model_fetch:
        fetch_model()  # no-op when the files are present and checksums match
    if not (MODEL_DIR / "config.json").is_file():
        print(f"Model files missing in {MODEL_DIR}. Run: python fetch_model.py", file=sys.stderr)
        return 1

    spec_path = ROOT / f"{args.name}.spec"
    spec_path.write_text(
        SPEC_TEMPLATE.format(
            collect_all=COLLECT_ALL,
            copy_metadata=COPY_METADATA,
            exclude=EXCLUDE,
            main_py=str(ROOT / "main.py"),
            root=str(ROOT),
            name=args.name,
        ),
        encoding="utf-8",
    )

    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean",
        "--distpath", str(ROOT / "dist"),
        "--workpath", str(ROOT / "build"),
        str(spec_path),
    ]
    print("+ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)

    # ship the model in its own directory beside the executable (not inside
    # _internal/), so it is never bundled twice and stays swappable
    bundle_dir = ROOT / "dist" / args.name
    model_dest = bundle_dir / "model"
    if model_dest.exists():
        shutil.rmtree(model_dest)
    shutil.copytree(MODEL_DIR, model_dest)

    total = sum(f.stat().st_size for f in bundle_dir.rglob("*") if f.is_file() and not f.is_symlink())
    print(f"\nBuild finished -> {bundle_dir}")
    print(f"Installed size: {total / 1e6:.1f} MB (model: {sum(f.stat().st_size for f in model_dest.iterdir()) / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
