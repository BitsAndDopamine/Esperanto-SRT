r"""Build the portable executable with PyInstaller (one folder per OS).

    .venv/bin/python build.py            # Linux/macOS -> dist/eo-srt/
    .venv\Scripts\python.exe build.py    # Windows -> dist\eo-srt\

What the bundle contains:
- Python runtime + app code + GUI (customtkinter/Tk) + numpy + soundfile.
- CPU-only ONNX Runtime + onnx-asr (no torch, NeMo, CUDA or TensorRT).
- The INT8 ASR model (~142 MB) in dist/eo-srt/model/, beside the executable.
  It is fetched at BUILD time by fetch_model.py (pinned HF commit, sha256
  verified); the app itself never downloads anything at runtime.
- The app icon (eo-srt.png): embedded into the Windows executable (PyInstaller
  converts the PNG to .ico; needs Pillow from the "build" extra) and bundled
  as data, where the GUI shows it in the window/taskbar on every OS.

The executable inside dist/eo-srt/ is renamed to carry the version:
eo-srt-v1.0-linux (Linux) / eo-srt-v1.0.exe (Windows). The version label
defaults to v<eo_srt.__version__> — the single source of the version (the
GUI's "pri" window shows it too); CI builds with the package version and
checks that the release tag matches it. Renaming is safe: a PyInstaller
onedir executable locates its _internal/ folder and the model/ directory
relative to its own path, not its name.

Why "-linux" and not just "eo-srt-v1.1": a Linux file name ending in a
single digit after a dot ("*.1".."*.9") is classified as a man page
(application/x-troff-man, a text type) by the shared MIME database — file
managers then open the binary in a text editor on double-click instead of
running it (the executable bit is unaffected). The "-linux" suffix keeps
the version in the name without that suffix. Windows uses the ".exe"
extension and has no such rule.

PyInstaller cannot cross-compile: run this once per target OS (Linux, Windows,
macOS). .github/workflows/build.yml does exactly that in CI, and packs the
bundle's *contents* (no top-level folder) into the release archives.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from eo_srt import __version__  # noqa: E402
from fetch_model import MODEL_DIR, fetch_model  # noqa: E402

# App icon (repo root): embedded into the Windows executable and bundled as
# data for the GUI's window/taskbar icon (see gui._icon_path).
ICON_PNG = ROOT / "eo-srt.png"

# Packages whose data/submodules/native libs PyInstaller's static analysis misses.
COLLECT_ALL = [
    "customtkinter",   # themes, fonts, assets
    "onnx_asr",        # preprocessors/data/*.onnx + fbanks.npz (read via importlib.resources)
    "onnxruntime",     # libonnxruntime + pybind state (CPU-only wheel)
    "soundfile",       # libsndfile binary (mp3/wav/ogg/flac decoding)
    "darkdetect",      # customtkinter's system-dark-mode probe
]

# dist metadata read via importlib.metadata at import time
COPY_METADATA = ["onnx-asr", "onnxruntime", "customtkinter"]

# Not used at runtime. Do NOT exclude stdlib test modules (unittest/pydoc):
# numpy.testing imports unittest and the frozen app crashed without it.
EXCLUDE = [
    "torch",
    "torchvision",
    "torchaudio",
    "nemo",
    "nemo_toolkit",
    "scipy",
    "pandas",
    "matplotlib",
    "IPython",
    "jupyter",
    "huggingface_hub",
    "cuda",
    "tensorrt",
    "tkinter.test",
]

SPEC_TEMPLATE = """# -*- mode: python ; coding: utf-8 -*-
# Generated by build.py — do not edit (gitignored build byproduct).
import os.path

from PyInstaller.utils.hooks import collect_all, copy_metadata

datas = []
binaries = []
hiddenimports = []
for pkg in {collect_all!r}:
    d, b, h = collect_all(pkg)
    datas += d
    binaries += b
    hiddenimports += h
for dist in {copy_metadata!r}:
    datas += copy_metadata(dist)

# the app icon, bundled at the bundle root (the GUI finds it via _MEIPASS)
datas.append(({icon_png!r}, '.'))

a = Analysis(
    [{main_py!r}],
    pathex=[{root!r}],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hooksconfig={{}},
    runtime_hooks=[],
    excludes={exclude!r},
    noarchive=False,
    optimize=0,
)

# Windows only: never ship ucrtbase.dll. When a bundled _internal/ucrtbase.dll
# exists, the PyInstaller bootloader pre-loads it before loading python312.dll;
# on Windows 10/11 that non-system UCRT copy then makes the Python DLL load fail
# ("Failed to load Python DLL ... LoadLibrary: Invalid access to memory location",
# error 998) and the exe dies before any Python code runs. The UCRT is part of
# the OS since Windows 10 — always use the system copy.
a.binaries = [
    entry for entry in a.binaries
    if os.path.basename(entry[0]).lower() != "ucrtbase.dll"
]

pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name={name!r},
    icon={icon!r},  # Windows: embedded into the exe (PNG converted to .ico); None elsewhere
    debug=False,
    bootloader_ignore_signals=False,
    strip=True,
    upx=False,
    console=True,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=True,
    upx=False,
    upx_exclude=[],
    name={name!r},
)
"""


def versioned_exe_name(base: str, version: str | None = None, platform: str | None = None) -> str:
    """File name of the built executable: the base name plus the version label.

    Windows: "eo-srt-v0.2.exe". Linux: "eo-srt-v0.2-linux" — the trailing
    "-linux" is deliberate: a name ending in ".<digit>" (like "eo-srt-v0.2")
    matches the "*.1".."*.9" man-page globs of the shared MIME database, so
    Linux file managers classify the binary as a text document and open it
    in a text editor on double-click instead of running it.
    """
    version = version or f"v{__version__}"
    platform = platform if platform is not None else sys.platform
    if platform.startswith("win"):
        return f"{base}-{version}.exe"
    if platform.startswith("linux"):
        return f"{base}-{version}-linux"
    if platform.startswith("darwin"):
        return f"{base}-{version}-macos"
    return f"{base}-{version}"


def exe_icon() -> str | None:
    """Icon for the built executable: eo-srt.png on Windows (PyInstaller embeds
    it, converting PNG -> .ico via Pillow), None elsewhere — a Linux ELF binary
    carries no icon; the taskbar/dock icon comes from the running window."""
    if sys.platform.startswith("win"):
        return str(ICON_PNG)
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--name", default="eo-srt",
                    help="base name of the bundle folder (dist/<name>/)")
    ap.add_argument("--version", default=None,
                    help="version label in the executable name, e.g. v0.2 "
                         "(default: v<eo_srt.__version__>; CI passes the release tag)")
    ap.add_argument("--skip-model-fetch", action="store_true",
                    help="do not download the model if missing (fail instead)")
    args = ap.parse_args()

    if not args.skip_model_fetch:
        fetch_model()  # no-op when the files are present and checksums match
    if not (MODEL_DIR / "config.json").is_file():
        print(f"Model files missing in {MODEL_DIR}. Run: python fetch_model.py", file=sys.stderr)
        return 1
    if not ICON_PNG.is_file():
        print(f"Icon file missing: {ICON_PNG}", file=sys.stderr)
        return 1

    spec_path = ROOT / f"{args.name}.spec"
    spec_path.write_text(
        SPEC_TEMPLATE.format(
            collect_all=COLLECT_ALL,
            copy_metadata=COPY_METADATA,
            exclude=EXCLUDE,
            main_py=str(ROOT / "main.py"),
            root=str(ROOT),
            name=args.name,
            icon=exe_icon(),
            icon_png=str(ICON_PNG),
        ),
        encoding="utf-8",
    )

    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean",
        "--distpath", str(ROOT / "dist"),
        "--workpath", str(ROOT / "build"),
        str(spec_path),
    ]
    print("+ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)

    bundle_dir = ROOT / "dist" / args.name

    # rename the executable to carry the version (see versioned_exe_name). A
    # PyInstaller onedir executable finds _internal/ and model/ relative to
    # its own path, so the new name does not affect startup or model lookup.
    old_exe = bundle_dir / (f"{args.name}.exe" if sys.platform.startswith("win") else args.name)
    new_exe = bundle_dir / versioned_exe_name(args.name, args.version)
    if new_exe != old_exe:
        if not old_exe.is_file():
            print(f"expected executable not found: {old_exe}", file=sys.stderr)
            return 1
        old_exe.rename(new_exe)
        print(f"Executable renamed: {old_exe.name} -> {new_exe.name}")

    # ship the model in its own directory beside the executable (not inside
    # _internal/), so it is never bundled twice and stays swappable
    model_dest = bundle_dir / "model"
    if model_dest.exists():
        shutil.rmtree(model_dest)
    shutil.copytree(MODEL_DIR, model_dest)

    total = sum(f.stat().st_size for f in bundle_dir.rglob("*") if f.is_file() and not f.is_symlink())
    print(f"\nBuild finished -> {bundle_dir}")
    print(f"Start it with: {new_exe}")
    print(f"Installed size: {total / 1e6:.1f} MB (model: {sum(f.stat().st_size for f in model_dest.iterdir()) / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
